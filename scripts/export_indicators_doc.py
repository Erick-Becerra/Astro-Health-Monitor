"""Writes docs/indicators.md from backend/shared/indicators.py (the single source of the rules).
    python scripts/export_indicators_doc.py
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from shared import indicators as I  # noqa: E402

NAME = {"green": "Normal", "yellow": "Caution", "orange": "Moderate risk", "red": "Critical"}


def num(x):
    if x in (math.inf, -math.inf):
        return None
    return f"{x:g}"


def span(lo, hi):
    a, b = num(lo), num(hi)
    if a is None:
        return f"< {b}"
    if b is None:
        return f">= {a}"
    return f"{a} to < {b}"


out = ["# Indicator rules (generated)", "",
       "Generated by `scripts/export_indicators_doc.py` from `backend/shared/indicators.py`. Do not edit by hand.",
       "The backend classifies each value as **Normal (green) / Caution (yellow) / Moderate risk (orange) / Critical (red)**;",
       "the front only paints. Ranges are `low <= value < high`.", ""]
for table, rows in I.RANGES.items():
    out += [f"## {I.LABEL.get(table, table)} (`{table}`)", "", "| Level | Range | Message | Action |", "|---|---|---|---|"]
    for level, lo, hi, side, key in rows:
        c = I.CONTENT.get(table, {}).get(key or level, {}) or I.CONTENT.get(table, {}).get(level, {})
        out.append(f"| {NAME[level]} | {span(lo, hi)} | {c.get('message', '')} | {c.get('action', '')} |".replace("\n", " "))
    out.append("")
    for k, c in I.CONTENT.get(table, {}).items():
        if c.get("procedure"):
            out += [f"**Procedure ({k}):**"] + [f"{i}. {s}" for i, s in enumerate(c["procedure"], 1)] + [""]
out += ["## Personal thresholds", "", "These indicators take per-astronaut thresholds that replace the high bands:", ""]
out += [f"- `{k}` (table `{v}`)" for k, v in I.ADJUSTABLE_TABLE.items()]
out += ["", "## Other rules", "",
        "- Activity state: heart rate and temperature use the at-rest, sleep or activity scale; the first 30 min after an exercise/EVA session use the activity scale.",
        "- Sleep: nights in a row under 6 h (2 = Moderate risk) and under 4 h (3 = Critical).",
        "- Reaction time (PVT) is judged against the astronaut's `baseline_pvt_ms` (default 300).",
        "- Signal quality: degraded = Caution; lost < 5 min = Caution; lost >= 5 min on a vital sensor = Critical; lost on other variables = Moderate risk. Lost values are not evaluated.",
        "- PHQ-9 / GAD-7 arrive in the packet as `mood_assessment`; PHQ-9 item 9 above 0 is always Critical with its own procedure.",
        "- Communication link (latency / link down) has its own level and does not change the crew level."]
(ROOT / "docs" / "indicators.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("docs/indicators.md written")
